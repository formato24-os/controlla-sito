import type { Referto } from "../index.js";
import { T } from "../lang.js";

const SIMBOLO = { ok: "✅", attenzione: "⚠️", problema: "❌", info: "ℹ️" } as const;
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** A report to paste in an issue, a PR comment or an email. */
export function markdown(r: Referto): string {
  const out = [
    `# ${T("Check-up di", "Check-up of")} ${r.host}: ${r.voto ?? "—"}/100`,
    "",
    `${T("Analizzato il", "Analysed on")} ${new Date(r.data).toLocaleString(T("it-IT", "en-GB"))} ${T("con", "with")} [controlla-sito](https://github.com/formato24-os/controlla-sito)${r.tecnologie.length ? ` · ${r.tecnologie.join(", ")}` : ""}`,
    "",
    `| ${T("Area", "Area")} | ${T("Voto", "Score")} |`,
    "|---|---:|",
    ...r.aree.map((a) => `| ${a.nome} | ${a.voto ?? "—"} |`),
  ];
  if (r.ai) {
    out.push("", `## ${T("Il parere dell'AI", "The AI's review")} (${r.ai.modello}, ${r.ai.voto}/100)`, "", r.ai.primaImpressione);
    if (r.ai.problemi.length) out.push("", ...r.ai.problemi.map((p) => `- **${p.titolo}**: ${p.dettaglio}`));
    if (r.ai.riscrittura) out.push("", `> ${T("Prima", "Before")}: ${r.ai.riscrittura.prima}`, ">", `> **${T("Dopo", "After")}: ${r.ai.riscrittura.dopo}**`);
    if (r.ai.piano.length) out.push("", `### ${T("Da dove partire", "Where to start")}`, "", ...r.ai.piano.map((p, i) => `${i + 1}. ${p.azione} (_${p.impatto}_)`));
  }
  for (const a of r.aree) {
    out.push("", `## ${a.nome} — ${a.voto ?? "—"}/100`, "", `| | ${T("Controllo", "Check")} | ${T("Risultato", "Result")} |`, "|---|---|---|");
    for (const x of a.controlli) out.push(`| ${SIMBOLO[x.esito]} | ${esc(x.titolo)} | ${esc(x.dettaglio)}${x.rimedio ? ` — _${esc(x.rimedio)}_` : ""} |`);
  }
  out.push("", "---", `${T("Generato da", "Generated by")} [controlla-sito](https://github.com/formato24-os/controlla-sito) · [Formato24](https://www.formato24.com)`);
  return out.join("\n");
}
